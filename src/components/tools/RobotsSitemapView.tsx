import React, { useState } from 'react';
import { Cpu, Download, Copy, Plus, Trash2, Check, FileText } from 'lucide-react';
import { copyToClipboard } from '../../services/storage';

export const RobotsSitemapView: React.FC = () => {
  const [tab, setTab] = useState<'robots' | 'sitemap'>('robots');

  // Robots state
  const [userAgent, setUserAgent] = useState('*');
  const [disallows, setDisallows] = useState<string[]>(['/admin/', '/private/', '/cart/']);
  const [allows, setAllows] = useState<string[]>(['/public/', '/blog/']);
  const [sitemapUrl, setSitemapUrl] = useState('https://example.com/sitemap.xml');
  const [crawlDelay, setCrawlDelay] = useState<number>(0);
  const [copiedRobots, setCopiedRobots] = useState(false);

  // Sitemap state
  const [urls, setUrls] = useState([
    { loc: 'https://example.com/', priority: '1.0', changefreq: 'daily', lastmod: '2026-11-01' },
    { loc: 'https://example.com/tools', priority: '0.9', changefreq: 'weekly', lastmod: '2026-11-02' },
    { loc: 'https://example.com/blog', priority: '0.8', changefreq: 'daily', lastmod: '2026-11-03' },
    { loc: 'https://example.com/pricing', priority: '0.7', changefreq: 'monthly', lastmod: '2026-10-15' },
  ]);
  const [copiedSitemap, setCopiedSitemap] = useState(false);

  // Generate robots text
  const generateRobotsTxt = () => {
    let out = `# robots.txt generated by PurelySEO\nUser-agent: ${userAgent}\n`;
    disallows.forEach(d => {
      if (d.trim()) out += `Disallow: ${d.trim()}\n`;
    });
    allows.forEach(a => {
      if (a.trim()) out += `Allow: ${a.trim()}\n`;
    });
    if (crawlDelay > 0) out += `Crawl-delay: ${crawlDelay}\n`;
    if (sitemapUrl.trim()) out += `\nSitemap: ${sitemapUrl.trim()}\n`;
    return out;
  };

  // Generate XML Sitemap
  const generateSitemapXml = () => {
    let out = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n`;
    urls.forEach(u => {
      out += `  <url>\n    <loc>${u.loc}</loc>\n    <lastmod>${u.lastmod}</lastmod>\n    <changefreq>${u.changefreq}</changefreq>\n    <priority>${u.priority}</priority>\n  </url>\n`;
    });
    out += `</urlset>`;
    return out;
  };

  const downloadFile = (content: string, filename: string, type: string) => {
    const blob = new Blob([content], { type });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10">
      <div className="mb-6">
        <div className="flex items-center gap-2 text-xs text-slate-500 mb-1">
          <span>Tools</span>
          <span>/</span>
          <span>Technical SEO</span>
          <span>/</span>
          <span className="text-slate-800 font-medium">Robots.txt &amp; XML Sitemap</span>
        </div>
        <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight">
          Robots.txt &amp; XML Sitemap Generator &amp; Validator
        </h1>
        <p className="text-xs sm:text-sm text-slate-600 mt-1 max-w-2xl">
          Create crawler directive instructions for Googlebot, Bingbot, and AI scrapers. Generate valid, compliant XML sitemaps ready for submission to Google Search Console.
        </p>
      </div>

      {/* Tabs */}
      <div className="flex items-center gap-2 mb-6 border-b border-slate-200 pb-2">
        <button
          onClick={() => setTab('robots')}
          className={`px-4 py-2 text-xs font-bold rounded-lg transition-colors ${
            tab === 'robots' ? 'bg-slate-900 text-white' : 'text-slate-600 hover:bg-slate-100'
          }`}
        >
          Robots.txt Generator
        </button>
        <button
          onClick={() => setTab('sitemap')}
          className={`px-4 py-2 text-xs font-bold rounded-lg transition-colors ${
            tab === 'sitemap' ? 'bg-slate-900 text-white' : 'text-slate-600 hover:bg-slate-100'
          }`}
        >
          XML Sitemap Generator
        </button>
      </div>

      {tab === 'robots' ? (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-8">
          {/* Left Form */}
          <div className="lg:col-span-6 bg-white p-6 rounded-xl border border-slate-200 shadow-sm space-y-4">
            <h2 className="text-xs font-bold text-slate-700 uppercase tracking-wider">
              Crawler Directives Configuration
            </h2>

            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">User Agent</label>
              <select
                value={userAgent}
                onChange={e => setUserAgent(e.target.value)}
                className="w-full p-2.5 text-xs bg-slate-50 border border-slate-200 rounded-lg text-slate-900"
              >
                <option value="*">* (All Crawlers &amp; Search Engines)</option>
                <option value="Googlebot">Googlebot (Google Primary)</option>
                <option value="Bingbot">Bingbot (Microsoft Bing)</option>
                <option value="GPTBot">GPTBot (OpenAI Scraper)</option>
                <option value="Google-Extended">Google-Extended (Gemini AI Scraper)</option>
              </select>
            </div>

            <div>
              <div className="flex justify-between items-center mb-1">
                <label className="text-xs font-semibold text-slate-700">Disallow Directories</label>
                <button
                  onClick={() => setDisallows([...disallows, '/new-folder/'])}
                  className="text-xs text-emerald-700 font-semibold hover:underline"
                >
                  + Add Disallow Path
                </button>
              </div>
              <div className="space-y-1.5">
                {disallows.map((dis, idx) => (
                  <div key={idx} className="flex gap-2">
                    <input
                      type="text"
                      value={dis}
                      onChange={e => {
                        const copy = [...disallows];
                        copy[idx] = e.target.value;
                        setDisallows(copy);
                      }}
                      className="flex-1 p-2 text-xs font-mono bg-slate-50 border border-slate-200 rounded"
                    />
                    <button
                      onClick={() => setDisallows(disallows.filter((_, i) => i !== idx))}
                      className="p-2 text-slate-400 hover:text-rose-600"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>
                  </div>
                ))}
              </div>
            </div>

            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                Sitemap Absolute URL
              </label>
              <input
                type="text"
                value={sitemapUrl}
                onChange={e => setSitemapUrl(e.target.value)}
                className="w-full p-2.5 text-xs font-mono bg-slate-50 border border-slate-200 rounded-lg"
              />
            </div>
          </div>

          {/* Right Preview */}
          <div className="lg:col-span-6 bg-slate-900 text-slate-100 p-6 rounded-xl border border-slate-800 shadow-sm flex flex-col justify-between">
            <div>
              <div className="flex items-center justify-between pb-3 border-b border-slate-800 text-xs">
                <span className="font-mono text-emerald-400">robots.txt</span>
                <div className="flex items-center gap-2">
                  <button
                    onClick={async () => {
                      await copyToClipboard(generateRobotsTxt());
                      setCopiedRobots(true);
                      setTimeout(() => setCopiedRobots(false), 2000);
                    }}
                    className="px-2.5 py-1 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded text-xs flex items-center gap-1"
                  >
                    <Copy className="w-3 h-3" />
                    <span>{copiedRobots ? 'Copied!' : 'Copy'}</span>
                  </button>
                  <button
                    onClick={() => downloadFile(generateRobotsTxt(), 'robots.txt', 'text/plain')}
                    className="px-2.5 py-1 bg-emerald-600 hover:bg-emerald-700 text-white rounded text-xs flex items-center gap-1 font-semibold"
                  >
                    <Download className="w-3 h-3" />
                    <span>Download</span>
                  </button>
                </div>
              </div>
              <pre className="mt-4 font-mono text-xs text-emerald-300 leading-relaxed overflow-x-auto whitespace-pre-wrap">
                {generateRobotsTxt()}
              </pre>
            </div>
            <div className="pt-4 border-t border-slate-800 text-[11px] text-slate-400">
              Upload this file directly to the root of your web server (e.g. https://yourdomain.com/robots.txt).
            </div>
          </div>
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-8">
          {/* Sitemap URLs Manager */}
          <div className="lg:col-span-6 bg-white p-6 rounded-xl border border-slate-200 shadow-sm space-y-4">
            <div className="flex justify-between items-center mb-1">
              <h2 className="text-xs font-bold text-slate-700 uppercase tracking-wider">
                Indexed URLs in Sitemap
              </h2>
              <button
                onClick={() =>
                  setUrls([
                    ...urls,
                    { loc: 'https://example.com/new-page', priority: '0.6', changefreq: 'weekly', lastmod: '2026-11-03' },
                  ])
                }
                className="text-xs text-emerald-700 font-semibold hover:underline"
              >
                + Add URL Entry
              </button>
            </div>

            <div className="space-y-3 max-h-[420px] overflow-y-auto pr-1">
              {urls.map((u, idx) => (
                <div key={idx} className="p-3 bg-slate-50 border border-slate-200 rounded-lg space-y-2">
                  <div className="flex items-center gap-2">
                    <input
                      type="text"
                      value={u.loc}
                      onChange={e => {
                        const copy = [...urls];
                        copy[idx].loc = e.target.value;
                        setUrls(copy);
                      }}
                      className="flex-1 p-1.5 text-xs font-mono bg-white border border-slate-200 rounded"
                    />
                    <button
                      onClick={() => setUrls(urls.filter((_, i) => i !== idx))}
                      className="p-1.5 text-slate-400 hover:text-rose-600"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>
                  </div>
                  <div className="grid grid-cols-2 gap-2 text-xs">
                    <div>
                      <span className="text-[10px] text-slate-500 uppercase block">Priority</span>
                      <select
                        value={u.priority}
                        onChange={e => {
                          const copy = [...urls];
                          copy[idx].priority = e.target.value;
                          setUrls(copy);
                        }}
                        className="w-full p-1 bg-white border border-slate-200 rounded text-xs"
                      >
                        <option value="1.0">1.0 (Highest)</option>
                        <option value="0.9">0.9</option>
                        <option value="0.8">0.8</option>
                        <option value="0.7">0.7</option>
                        <option value="0.6">0.6</option>
                        <option value="0.5">0.5</option>
                      </select>
                    </div>
                    <div>
                      <span className="text-[10px] text-slate-500 uppercase block">Changefreq</span>
                      <select
                        value={u.changefreq}
                        onChange={e => {
                          const copy = [...urls];
                          copy[idx].changefreq = e.target.value;
                          setUrls(copy);
                        }}
                        className="w-full p-1 bg-white border border-slate-200 rounded text-xs"
                      >
                        <option value="always">always</option>
                        <option value="hourly">hourly</option>
                        <option value="daily">daily</option>
                        <option value="weekly">weekly</option>
                        <option value="monthly">monthly</option>
                      </select>
                    </div>
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* XML Output */}
          <div className="lg:col-span-6 bg-slate-900 text-slate-100 p-6 rounded-xl border border-slate-800 shadow-sm flex flex-col justify-between">
            <div>
              <div className="flex items-center justify-between pb-3 border-b border-slate-800 text-xs">
                <span className="font-mono text-emerald-400">sitemap.xml</span>
                <div className="flex items-center gap-2">
                  <button
                    onClick={async () => {
                      await copyToClipboard(generateSitemapXml());
                      setCopiedSitemap(true);
                      setTimeout(() => setCopiedSitemap(false), 2000);
                    }}
                    className="px-2.5 py-1 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded text-xs flex items-center gap-1"
                  >
                    <Copy className="w-3 h-3" />
                    <span>{copiedSitemap ? 'Copied!' : 'Copy'}</span>
                  </button>
                  <button
                    onClick={() => downloadFile(generateSitemapXml(), 'sitemap.xml', 'application/xml')}
                    className="px-2.5 py-1 bg-emerald-600 hover:bg-emerald-700 text-white rounded text-xs flex items-center gap-1 font-semibold"
                  >
                    <Download className="w-3 h-3" />
                    <span>Download XML</span>
                  </button>
                </div>
              </div>
              <pre className="mt-4 font-mono text-xs text-emerald-300 leading-relaxed overflow-x-auto max-h-[360px] overflow-y-auto whitespace-pre">
                {generateSitemapXml()}
              </pre>
            </div>
            <div className="pt-4 border-t border-slate-800 text-[11px] text-slate-400">
              Submit your sitemap URL directly to Google Search Console for automated indexing.
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
